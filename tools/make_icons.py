"""Generates the app icon for both platforms from one drawing.

    python tools/make_icons.py

The drawing is in the 108x108 space of an Android adaptive icon (the launcher shows roughly the middle 72x72, the
key shapes stay inside the 66-unit safe circle). Outputs:
  - android/app/src/main/res/drawable/ic_launcher_{foreground,monochrome}.xml + mipmap-anydpi-v26/ic_launcher*.xml
  - ios/AppIcon/Assets.xcassets/AppIcon.appiconset/AppIcon.png (1024 px, the visible 72x72 part, no transparency)
"""
import json
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ORANGE = "#FF9500"  # Theme.orange
ROAD = "#2B2B30"
WHITE = "#FFFFFF"

ROAD_POLY = [(47, 20), (61, 20), (86, 108), (22, 108)]
DASHES = [(53.5, 22, 54.5, 27), (53.2, 31, 54.8, 38), (52.4, 82, 55.6, 94)]
BOX = (32, 44, 76, 76)  # counting box, as drawn by the app: white outline, light fill, round corner handles
BOX_RADIUS = 3
BOX_STROKE = 3
DOT_OUTER, DOT_INNER = 3.4, 2.0
CAR = (47.5, 49, 60.5, 71)
CAR_RADIUS = 4
WINDSHIELD = [(49.5, 54), (58.5, 54), (57.5, 58), (50.5, 58)]
REAR_WINDOW = [(50.5, 65.5), (57.5, 65.5), (58.5, 68), (49.5, 68)]


def corners():
    x0, y0, x1, y1 = BOX
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]


# ---------- Android vector drawables ----------

def f(v):
    return f"{v:g}"


def poly(points):
    return "M" + " L".join(f"{f(x)},{f(y)}" for x, y in points) + " Z"


def rrect(x0, y0, x1, y1, r):
    return (f"M{f(x0 + r)},{f(y0)} H{f(x1 - r)} A{f(r)},{f(r)} 0 0 1 {f(x1)},{f(y0 + r)} V{f(y1 - r)} "
            f"A{f(r)},{f(r)} 0 0 1 {f(x1 - r)},{f(y1)} H{f(x0 + r)} A{f(r)},{f(r)} 0 0 1 {f(x0)},{f(y1 - r)} "
            f"V{f(y0 + r)} A{f(r)},{f(r)} 0 0 1 {f(x0 + r)},{f(y0)} Z")


def circle(cx, cy, r):
    return f"M{f(cx - r)},{f(cy)} A{f(r)},{f(r)} 0 1 0 {f(cx + r)},{f(cy)} A{f(r)},{f(r)} 0 1 0 {f(cx - r)},{f(cy)} Z"


def vector(paths):
    body = "\n".join(paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
"""


def fill(d, color):
    return f'    <path android:fillColor="{color}" android:pathData="{d}" />'


def android():
    res = os.path.join(ROOT, "android/app/src/main/res")
    box = rrect(*BOX, BOX_RADIUS)
    fg = [fill(poly(ROAD_POLY), ROAD)]
    fg += [fill(poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)]), WHITE) for x0, y0, x1, y1 in DASHES]
    fg.append(f'    <path android:fillColor="#38FFFFFF" android:strokeColor="{WHITE}" '
              f'android:strokeWidth="{BOX_STROKE}" android:pathData="{box}" />')
    fg.append(fill(rrect(*CAR, CAR_RADIUS), WHITE))
    fg.append(fill(poly(WINDSHIELD) + " " + poly(REAR_WINDOW), ROAD))
    for cx, cy in corners():
        fg.append(fill(circle(cx, cy, DOT_OUTER), WHITE))
        fg.append(fill(circle(cx, cy, DOT_INNER), ORANGE))
    # themed icon (Android 13+): only the alpha counts, so just the box, its handles and the car
    mono = [f'    <path android:strokeColor="{WHITE}" android:strokeWidth="{BOX_STROKE}" android:pathData="{box}" />',
            fill(rrect(*CAR, CAR_RADIUS), WHITE)]
    mono += [fill(circle(cx, cy, DOT_OUTER), WHITE) for cx, cy in corners()]

    os.makedirs(os.path.join(res, "drawable"), exist_ok=True)
    os.makedirs(os.path.join(res, "mipmap-anydpi-v26"), exist_ok=True)
    with open(os.path.join(res, "drawable/ic_launcher_foreground.xml"), "w", newline="\n") as out:
        out.write(vector(fg))
    with open(os.path.join(res, "drawable/ic_launcher_monochrome.xml"), "w", newline="\n") as out:
        out.write(vector(mono))
    with open(os.path.join(res, "values/ic_launcher_background.xml"), "w", newline="\n") as out:
        out.write(f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icons.py -->\n'
                  f'<resources>\n    <color name="ic_launcher_background">{ORANGE}</color>\n</resources>\n')
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        with open(os.path.join(res, "mipmap-anydpi-v26", name), "w", newline="\n") as out:
            out.write(adaptive)


# ---------- iOS PNG ----------

def render(size, visible=(18, 90)):
    """The visible part of the 108 space, supersampled 4x for smooth edges."""
    ss = size * 4
    lo, hi = visible
    s = ss / (hi - lo)

    def p(x, y):
        return ((x - lo) * s, (y - lo) * s)

    img = Image.new("RGBA", (ss, ss), ORANGE)
    d = ImageDraw.Draw(img)
    d.polygon([p(x, y) for x, y in ROAD_POLY], fill=ROAD)
    for x0, y0, x1, y1 in DASHES:
        d.rectangle([p(x0, y0), p(x1, y1)], fill=WHITE)

    overlay = Image.new("RGBA", (ss, ss), (0, 0, 0, 0))
    ImageDraw.Draw(overlay).rounded_rectangle([p(*BOX[:2]), p(*BOX[2:])], radius=BOX_RADIUS * s, fill=(255, 255, 255, 56))
    img = Image.alpha_composite(img, overlay)
    d = ImageDraw.Draw(img)
    half = BOX_STROKE / 2
    d.rounded_rectangle([p(BOX[0] - half, BOX[1] - half), p(BOX[2] + half, BOX[3] + half)],
                        radius=(BOX_RADIUS + half) * s, outline=WHITE, width=round(BOX_STROKE * s))
    d.rounded_rectangle([p(*CAR[:2]), p(*CAR[2:])], radius=CAR_RADIUS * s, fill=WHITE)
    d.polygon([p(x, y) for x, y in WINDSHIELD], fill=ROAD)
    d.polygon([p(x, y) for x, y in REAR_WINDOW], fill=ROAD)
    for cx, cy in corners():
        for r, c in ((DOT_OUTER, WHITE), (DOT_INNER, ORANGE)):
            d.ellipse([p(cx - r, cy - r), p(cx + r, cy + r)], fill=c)
    return img.resize((size, size), Image.LANCZOS).convert("RGB")


def ios():
    catalog = os.path.join(ROOT, "ios/AppIcon/Assets.xcassets")
    iconset = os.path.join(catalog, "AppIcon.appiconset")
    os.makedirs(iconset, exist_ok=True)
    render(1024).save(os.path.join(iconset, "AppIcon.png"))
    info = {"author": "xcode", "version": 1}
    with open(os.path.join(catalog, "Contents.json"), "w", newline="\n") as out:
        json.dump({"info": info}, out, indent=2)
    with open(os.path.join(iconset, "Contents.json"), "w", newline="\n") as out:
        json.dump({"images": [{"filename": "AppIcon.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"}],
                   "info": info}, out, indent=2)


if __name__ == "__main__":
    android()
    ios()
    print("icons written")
